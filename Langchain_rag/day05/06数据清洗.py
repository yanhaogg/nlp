import re


#1.去除多余空格
# 示例文本
text = "AI is coming"
# 替换多个空格为一个空格
text = re.sub(r"\s+", " ", text)
print(text)
# 输出: "AI is coming"


#2.去除多余换行
text = "人工智能\n\n是未来的发展方向\n\n\n机器学习是其重要分支"
# 连续换行替换成一个换行
text = re.sub(r"\n+", "\n", text)
print(text)
# 输出:
# 人工智能
# 是未来的发展方向
# 机器学习是其重要分支


#3.去除特殊字符
# 示例文本
text = "@@@@@\n*****\n人工智能是未来的方向\n#####"
# 删除常见特殊字符
text = re.sub(r"[@#*■□]+", "", text)
print(text)
# 输出:
# 人工智能是未来的方向


