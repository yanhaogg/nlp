# 1.先获取加载出来的文本
# 2.把字符分割成单个字,split('')或者list()
# 3.使用集合去重,去掉  [\u4e00-\u9fa5a-zA-Z0-9]
# 4.看看有哪些剩余的字符,去掉常见的字符,比如(,.!?:'*#等)
# 5.把剩下的全部堆到 r'[]' 中,对原文进行全部去除