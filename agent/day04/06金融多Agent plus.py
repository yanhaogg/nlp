from crewai import Agent, Task, Crew, Process, LLM
from crewai.tools import tool
import wikipedia
from dotenv import load_dotenv
load_dotenv()

# ================  项目说明   ==================
# 项目 : 多Agent协作生成《量子计算对金融行业的影响》专业短文
# 流水线 : 研究员(信息检索与提炼) -> 作家(内容创作) -> 校验专家(质量审校)
# 设计要点 :
#   1. 三个Agent使用差异化的temperature策略: 研究(默认) / 创作(高发散) / 校验(低随机)
#   2. Task描述采用"背景-步骤-格式-质量标准"四段式结构, 提升输出稳定性
#   3. 校验环节强制输出"修改前后条文对比表", 保证审校过程可追溯

# ================ 1. 定义工具  ===================
@tool
def wikipedia_search(query: str) -> str:
    '''使用维基百科API搜索信息(支持中文)。输入查询关键词，返回词条标题与摘要。'''
    try:
        wikipedia.set_lang("zh")
        page = wikipedia.page(query, auto_suggest=False)
        return f"标题 : {page.title}\n摘要 : {page.summary}"
    except wikipedia.DisambiguationError as e:
        options = e.options[:3]
        return f"模糊匹配 : 请从以下选项中选择: {','.join(options)}"
    except wikipedia.PageError:
        return "未找到相关信息"
    except Exception as e:
        return f"搜索错误 : {str(e)}"

# ================ 2. 定义 Agent  ===============
researcher = Agent(
    role="量子计算与金融科技领域高级研究员",
    goal=(
        "围绕『量子计算对金融行业的影响』这一主题，从权威来源检索并交叉验证信息，"
        "提炼出3个最具代表性、相互独立且有事实支撑的核心观点，"
        "为下游写作环节提供结构化、可直接引用的研究素材。"
    ),
    backstory=(
        "你拥有量子信息科学与金融工程双重背景，曾在头部金融科技研究院从事前沿技术产业化评估工作，"
        "主导过多份量子计算在风险建模、投资组合优化、加密安全等场景的行业研究报告。"
        "你的工作准则是：所有观点必须有来源依据，绝不编造数据；"
        "当检索结果不足时，你会明确标注『信息有限』而非臆测。"
        "你输出的研究素材以结构清晰、颗粒度适中著称，深受写作团队信赖。"
    ),
    tools=[wikipedia_search],
    llm=LLM(model="deepseek-v4-flash"),
    verbose=True,
)

writer = Agent(
    role="资深金融科技专栏作家",
    goal=(
        "严格基于研究员提供的核心观点（不得引入未经验证的新事实），"
        "撰写一篇面向金融从业者的500字（±10%）短文，"
        "做到结构完整、逻辑递进、术语准确且通俗易懂。"
    ),
    backstory=(
        "你是一位拥有十年财经媒体经验的科技专栏作家，长期为主流金融媒体撰写前沿技术评论，"
        "擅长用『技术原理→行业场景→影响与展望』的叙事框架，把晦涩的技术概念转化为决策者能读懂的语言。"
        "你的写作纪律是：只使用上游研究素材中的事实，字数严格受控，"
        "开头必须点题，结尾必须给出前瞻性判断，全文避免空洞的套话。"
    ),
    llm=LLM(model="deepseek-v4-flash", temperature=1.2, top_p=0.92),
    verbose=True,
)

validator = Agent(
    role="金融内容合规与质量审校专家",
    goal=(
        "对文章进行事实准确性、逻辑连贯性、术语规范性与可读性的四维审校，"
        "输出最终定稿，并以『修改前后条文对比表』的形式完整记录每一处修改及其理由，"
        "确保审校过程透明、可追溯。"
    ),
    backstory=(
        "你曾在大型金融机构担任内容合规审核负责人，主导过上百篇对外研究报告的终审工作，"
        "对事实错误、逻辑跳跃、夸大表述零容忍。"
        "你的审校方法论是『逐句核对、有据修改、留痕可查』：每一处改动都必须给出修改前原文、"
        "修改后文本和修改理由三要素；对于无需修改的部分，你会明确说明『保持原文』，绝不为改而改。"
    ),
    llm=LLM(model="deepseek-v4-flash", temperature=0.2, top_p=0.6),
    verbose=True,
)

# ================  3. 定义三个 Task (带依赖关系)  =========
task1 = Task(
    description=(
        "【任务背景】\n"
        "团队需要产出一篇《量子计算对金融行业的影响》专业短文，你负责上游研究环节，"
        "你的输出将直接作为写作素材，质量决定全文上限。\n\n"
        "【执行步骤】\n"
        "1. 使用 wikipedia_search 工具检索『量子计算』『量子计算 金融』等相关词条；\n"
        "2. 若遇到模糊匹配，从返回选项中选择最相关词条重新检索；\n"
        "3. 从检索结果中筛选与金融行业直接相关的信息（如风险建模、组合优化、加密安全）；\n"
        "4. 提炼出3个相互独立、最具代表性的核心观点，并为每个观点撰写依据说明。\n\n"
        "【输出格式】\n"
        "使用 Markdown 格式，包含：\n"
        "- 一张核心观点汇总表，列为：| 序号 | 核心观点 | 依据与解释 | 信息来源 |\n"
        "- 表格下方补充1段研究备注（说明信息局限性，如有）。\n\n"
        "【质量标准】\n"
        "1. 3个观点互不重叠，覆盖不同金融场景；\n"
        "2. 每个观点的解释为1-2句话，有事实依据，不得臆造数据；\n"
        "3. 检索失败时须如实标注，不得虚构来源。"
    ),
    expected_output=(
        "一份Markdown研究简报：含核心观点汇总表（序号/核心观点/依据与解释/信息来源 四列，共3行）"
        "及一段研究备注。"
    ),
    agent=researcher,
)

task2 = Task(
    description=(
        "【任务背景】\n"
        "研究员已完成核心观点提炼（见上下文），你需要将其转化为一篇面向金融从业者的专业短文，"
        "文章将进入终审环节，须为审校预留清晰的段落结构。\n\n"
        "【执行步骤】\n"
        "1. 通读研究简报，确认3个核心观点及其依据；\n"
        "2. 按『引言点题 → 三个观点逐段展开 → 总结展望』的五段式结构组织文章；\n"
        "3. 每个观点段落须包含：观点陈述 + 金融场景举例 + 影响分析；\n"
        "4. 通读全文，控制字数在450-550字之间。\n\n"
        "【输出格式】\n"
        "Markdown 格式，包含：\n"
        "- 文章标题（一级标题）；\n"
        "- 正文五段；\n"
        "- 文末附一张文章结构自查表：| 段落 | 核心内容 | 对应研究观点 | 字数 |\n\n"
        "【质量标准】\n"
        "1. 全部事实只来源于研究简报，不得新增未经验证的信息；\n"
        "2. 字数450-550字（不含标题与自查表）；\n"
        "3. 术语准确、行文流畅，避免口语化与空洞套话。"
    ),
    expected_output=(
        "一篇结构完整的Markdown短文：含标题、450-550字正文（五段式），"
        "及文末结构自查表（段落/核心内容/对应研究观点/字数）。"
    ),
    agent=writer,
    context=[task1],
)

task3 = Task(
    description=(
        "【任务背景】\n"
        "文章初稿已完成，你是发布前的最后一道质量关口。你的审校记录须完整留痕，"
        "供项目复盘与质量追溯使用，其中『修改前后条文对比』是本任务的核心交付物。\n\n"
        "【执行步骤】\n"
        "1. 事实核查：将文章中的每处事实陈述与研究简报（task1输出）逐一比对；\n"
        "2. 逻辑审查：检查段落衔接、论证链条是否连贯，有无跳跃或自相矛盾；\n"
        "3. 语言润色：修正术语误用、语病及可读性问题；\n"
        "4. 字数复核：确认正文在450-550字范围内；\n"
        "5. 汇总所有修改，逐条记录修改前原文、修改后文本与修改理由，产出终稿。\n\n"
        "【输出格式】\n"
        "Markdown 格式，依次包含三部分：\n"
        "## 一、最终定稿文章（标题+正文）\n"
        "## 二、修改前后条文对比表（核心交付物，必须输出）：\n"
        "| 序号 | 位置(段落) | 修改前原文 | 修改后文本 | 修改类型(事实/逻辑/语言) | 修改理由 |\n"
        "## 三、审校结论：一段总体评价（含终稿字数、遗留风险提示）。\n\n"
        "【质量标准】\n"
        "1. 对比表须覆盖全部修改点，原文引用必须逐字准确，不得概述；\n"
        "2. 若某维度检查无问题，须在审校结论中明确写出『XX维度：未发现问题』；\n"
        "3. 若全文无需修改，对比表中填写一行『全文通过，无修改』并说明理由；\n"
        "4. 只做必要修改，禁止为改而改，禁止改变文章原意。"
    ),
    expected_output=(
        "一份Markdown审校报告：①最终定稿文章；②修改前后条文对比表"
        "（序号/位置/修改前原文/修改后文本/修改类型/修改理由 六列）；③审校结论。"
    ),
    agent=validator,
    context=[task1, task2],
)

# ================  4. 组建 crew  ==============
crew = Crew(
    agents=[researcher, writer, validator],
    tasks=[task1, task2, task3],
    process=Process.sequential,
    verbose=True,
)

res = crew.kickoff()
print(res.raw)
